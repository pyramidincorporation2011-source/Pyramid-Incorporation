/**
 * Generates third-party notices (licences and credits) for everything the live site uses:
 *   - public/third-party-notices.txt  (published with the site, linked from the footer)
 *   - THIRD_PARTY_NOTICES.md           (kept in the repository)
 *
 * Open-source packages: every package bundled into the site (production dependencies and their
 * dependencies), with the full licence text taken from node_modules.
 * Photos, quoted content and trademarks: from src/data/credits.js.
 *
 * Runs automatically as part of `npm run build`. Manual run: node scripts/generate-notices.mjs
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nm = path.join(root, 'node_modules');
const { photoCredits, otherSources, trademarks } = await import(pathToFileURL(path.join(root, 'src/data/credits.js')).href);

// Walk production dependencies recursively.
const pkgJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const seen = new Map();
async function visit(name) {
  if (seen.has(name)) return;
  const dir = path.join(nm, name);
  if (!existsSync(path.join(dir, 'package.json'))) return;
  const pkg = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'));
  const files = await readdir(dir);
  const licFile = files.find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  const text = licFile ? (await readFile(path.join(dir, licFile), 'utf8')).trim() : '';
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  seen.set(name, {
    name,
    version: pkg.version,
    license: pkg.license || (typeof pkg.licenses?.[0] === 'object' ? pkg.licenses[0].type : 'See licence text'),
    homepage: pkg.homepage || (repo ? repo.replace(/^git\+/, '').replace(/\.git$/, '') : ''),
    text,
  });
  for (const dep of Object.keys(pkg.dependencies || {})) await visit(dep);
}
for (const dep of Object.keys(pkgJson.dependencies || {})) await visit(dep);
const packages = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));

const rule = '='.repeat(78);
const thin = '-'.repeat(78);
const year = new Date().getFullYear();

// ---------- Plain-text version (published) ----------
let txt = `THIRD-PARTY NOTICES AND CREDITS
www.pyramidincorporation.com

The website of Pyramid Incorporation is (c) ${year} Pyramid Incorporation, all rights
reserved. It includes the third-party material listed below, which remains the
property of its respective owners and is used under the licences stated.

${rule}
1. PHOTOGRAPHS
${rule}

Stock photographs are from Pexels and are used under the Pexels License
(https://www.pexels.com/license/). They are shown for illustration only and are
labelled "Representative image" where they appear in the project gallery.

`;
for (const p of photoCredits) txt += `- ${p.use}\n  Photo by ${p.photographer} on Pexels\n  ${p.url}\n\n`;

txt += `${rule}
2. OTHER CONTENT AND SOURCES
${rule}

${otherSources.map((s) => `- ${s}`).join('\n')}

${rule}
3. TRADEMARKS
${rule}

${trademarks}

${rule}
4. OPEN-SOURCE SOFTWARE AND FONTS
${rule}

The site is built with the following open-source packages. Their licences are
reproduced in full below, as those licences require.

`;
for (const p of packages) txt += `- ${p.name} ${p.version} (${p.license})${p.homepage ? `  ${p.homepage}` : ''}\n`;
for (const p of packages) {
  txt += `\n${thin}\n${p.name} ${p.version}\nLicence: ${p.license}\n${thin}\n\n${p.text || '(No licence file is included in this package; see its homepage.)'}\n`;
}
await writeFile(path.join(root, 'public/third-party-notices.txt'), txt.replace(/\r\n/g, '\n'));

// ---------- Markdown version (repository) ----------
let md = `# Third-party notices and credits

The Pyramid Incorporation website is © ${year} Pyramid Incorporation, all rights reserved (see [LICENSE](LICENSE)).
It includes the third-party material below, which remains the property of its respective owners and is used under
the licences stated. A plain-text copy with full licence texts is published at \`/third-party-notices.txt\`.

> This file is generated by \`scripts/generate-notices.mjs\` during \`npm run build\`. Edit \`src/data/credits.js\`
> rather than this file.

## Photographs

Stock photographs from [Pexels](https://www.pexels.com/), used under the [Pexels License](https://www.pexels.com/license/).
They illustrate the type of work only, and are labelled "Representative image" in the project gallery.

| Used for | Photographer | Source |
| --- | --- | --- |
${photoCredits.map((p) => `| ${p.use} | ${p.photographer} | [Pexels](${p.url}) |`).join('\n')}

## Other content and sources

${otherSources.map((s) => `- ${s}`).join('\n')}

## Trademarks

${trademarks}

## Open-source software and fonts

| Package | Version | Licence |
| --- | --- | --- |
${packages.map((p) => `| ${p.homepage ? `[${p.name}](${p.homepage})` : p.name} | ${p.version} | ${p.license} |`).join('\n')}

Full licence texts are reproduced in \`public/third-party-notices.txt\`.
`;
await writeFile(path.join(root, 'THIRD_PARTY_NOTICES.md'), md);
console.log(`Notices written: ${packages.length} packages, ${photoCredits.length} photos.`);
